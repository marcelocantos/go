// The conversions between decimal values and text are those of
// internal/bid: parseDecimal reads its input with bid.Parse64 or
// bid.Parse128 once decimal_parse.go has put Go's syntax into the kernel's,
// and formatDecimal and appendDecimal take the coefficient digits, sign and
// quantum from bid.UnpackDigits128, or from bid.UBDUnpackDigits128 where
// decimal128 is stored as UBD (see decimalWords). This file owns the format verbs and
// precision, and the layout of the digits that follows from them. Whenever
// a precision asks for fewer digits than a value has, the value is
// rounded by the kernel's Quantize.

// formatDecimal converts a decimal128 value to a string.
// The format fmt and precision prec follow the same rules as [FormatFloat],
// except for the special precision -1. For a binary float that means the
// fewest digits that round-trip the value. A decimal value also has a quantum,
// so it means all the digits of the coefficient: 1.50 formats as "1.50", and
// [parseDecimal] of that string returns the same value and quantum.
//
// With 'g' and 'G' and the special precision -1, the result is the canonical
// string, which println and fmt's %v also write. It follows a float's
// shortest form: fixed notation unless the exponent of the leading digit is
// less than -4 or at least 6, and an exponent of at least two digits
// ("1e-05", "1.5e+06"). Unlike a float it keeps every coefficient digit, and
// a quantum above the units digit, which fixed notation can't show, forces
// exponential notation: 1e+03 is not 1000.
//
// The bitSize must be 64 for values from decimal64 or 128 for decimal128.
//
//go:linkname formatDecimal
func formatDecimal(d decimal128, fmt byte, prec int, bitSize int) string {
	// The canonical form fits on the stack. Explicit fixed-point formats
	// and large precisions may grow past this buffer through append.
	var buf [bid.MaxLen128]byte
	return string(appendDecimal(buf[:0], d, fmt, prec, bitSize))
}

// appendDecimal appends the string form of the decimal128 value d,
// as generated by formatDecimal, to dst and returns the extended buffer.
// The bitSize must be 64 for values widened from decimal64 or 128 for decimal128.
//
//go:linkname appendDecimal
func appendDecimal(dst []byte, d decimal128, fmt byte, prec int, bitSize int) []byte {
	// A decimal64 widens exactly, with the same coefficient and exponent,
	// so both widths have the same digits and the same rounding.
	_ = bitSize

	x := decimalWords(d)

	switch fmt {
	case 'e', 'E', 'f', 'g', 'G':
	case 'b':
		return appendDecimalB(dst, x)
	case 'x', 'X':
		return appendDecimalX(dst, x, fmt, prec, bitSize)
	default:
		// As FormatFloat does: the specials whatever the format, and
		// otherwise "%" and the format.
		switch kind, neg, _, _ := unpackDecimal(x); kind {
		case bid.KindNaN:
			return append(dst, "NaN"...)
		case bid.KindInf:
			if neg {
				return append(dst, "-Inf"...)
			}
			return append(dst, "+Inf"...)
		}
		return append(dst, '%', fmt)
	}

	// A short coefficient at or just below the units place and below 10^6
	// (money and most quantities) is plain digits around a point in every
	// notation that keeps all the digits, which is each verb but 'e' and
	// 'E' at precision -1. The kernel lays those out in registers and stores
	// them straight into dst, exactly the bytes appended.
	if i := len(dst); isShortDecimal(x) && prec < 0 && fmt != 'e' && fmt != 'E' && cap(dst)-i >= bid.ShortLen128 {
		sign, frac := shortParts(x)
		return dst[:i+bid.PutShort128((*[bid.ShortLen128]byte)(dst[i:i+bid.ShortLen128]), sign, frac, x.Lo)]
	}

	// A coefficient of nine digits or more, in the canonical form: the
	// kernel converts the digits eight at a time and stores the whole form
	// in place, exactly the bytes appended. It asks for the room of the
	// longest form, which formatDecimal's buffer and fmt's have; with less
	// it lays the form out in a buffer of its own.
	if prec < 0 && isLongDecimal(x) && fmt != 'e' && fmt != 'E' && fmt != 'f' && fmt != 'G' {
		sign, exp, c := longParts(x)
		if i := len(dst); cap(dst)-i >= bid.LongLen128 {
			return dst[:i+bid.PutLong128((*[bid.LongLen128]byte)(dst[i:i+bid.LongLen128]), sign, exp, c)]
		}
		var buf [bid.LongLen128]byte
		return append(dst, buf[:bid.PutLong128(&buf, sign, exp, c)]...)
	}

	var digs [bid.Precision128]byte
	kind, neg, n, exp := unpackDigitsDecimal(&digs, x)
	switch kind {
	case bid.KindNaN:
		return append(dst, "NaN"...)
	case bid.KindInf:
		if neg {
			return append(dst, "-Inf"...)
		}
		return append(dst, "+Inf"...)
	}

	if prec < 0 {
		// Canonical output keeps all coefficient digits and the quantum. Keep
		// its layout here so it needs neither a call nor the rounding state.
		format := normalFormat(fmt)
		digits := digs[len(digs)-n:]
		if n == 0 {
			digits = []byte{'0'}
		}
		if neg {
			dst = append(dst, '-')
		}
		switch format {
		case 'e', 'E':
			return appendExp(dst, digits, exp, format, -1)
		case 'f':
			if n == 0 {
				exp = min(exp, 0)
			}
			return appendFixed(dst, digits, exp, -1)
		}
		e := exp + len(digits) - 1
		if e < canonicalMinExp || e >= canonicalMaxExp || exp > 0 {
			ef := byte('e')
			if format == 'G' {
				ef = 'E'
			}
			return appendExp(dst, digits, exp, ef, -1)
		}
		if exp == 0 {
			return append(dst, digits...)
		}
		// The canonical fixed form neither rounds nor pads when the point is
		// inside the coefficient. Reserve the whole result once, then place
		// the two digit spans without the general formatter's append checks.
		point := len(digits) + exp
		if point > 0 && cap(dst)-len(dst) >= len(digits)+1 {
			start := len(dst)
			dst = dst[:start+len(digits)+1]
			// Small spans cost less to place directly than to dispatch two
			// variable-size copies. The ARM64 length sweep crosses over at
			// ten digits; retain bulk copying above the measured short range.
			const directDigits = 9
			if len(digits) <= directDigits {
				for i := 0; i < point; i++ {
					dst[start+i] = digits[i]
				}
				dst[start+point] = '.'
				for i := point; i < len(digits); i++ {
					dst[start+i+1] = digits[i]
				}
			} else {
				copyDecimalDigits(dst[start:], digits[:point])
				dst[start+point] = '.'
				copyDecimalDigits(dst[start+point+1:], digits[point:])
			}
			return dst
		}
		return appendFixed(dst, digits, exp, -1)
	}
	v := finite{neg: neg, n: n, exp: exp, digs: &digs}
	if v.n > 0 {
		v.round(x, normalFormat(fmt), prec)
	}
	if v.n == 0 {
		return appendZero(dst, v.neg, fmt, prec)
	}
	return formatDigits(dst, v.neg, v.exp, v.digs[len(v.digs)-v.n:], normalFormat(fmt), prec)
}

// decimalWords returns the words of d in the encoding the kernel formats
// it in: decimal128's own where that is UBD (bid.NativeUBD128), which
// formats with no conversion, and otherwise BID. The functions below read
// the words in that encoding; bid.NativeUBD128 is a constant, so each is a
// single kernel call.
func decimalWords(d decimal128) bid.Uint128 {
	if bid.NativeUBD128 {
		hi, lo := decimal.Bits128(d)
		return bid.Uint128{Hi: hi, Lo: lo}
	}
	hi, lo := decimal.BID128bits(d)
	return bid.Uint128{Hi: hi, Lo: lo}
}

func ubdWords(x bid.Uint128) bid.UBD128 { return bid.UBD128{Lo: x.Lo, Hi: x.Hi} }

func isShortDecimal(x bid.Uint128) bool {
	if bid.NativeUBD128 {
		return bid.UBDIsShort128(ubdWords(x))
	}
	return bid.IsShort128(x)
}

// shortParts returns the sign (0 or 1) and the places after the point of
// x, a value isShortDecimal accepts, for bid.PutShort128.
func shortParts(x bid.Uint128) (sign, frac uint) {
	if bid.NativeUBD128 {
		return uint(x.Hi >> bid.UBDSignShift & 1), uint(-(int64(x.Hi) >> bid.UBDExpShift))
	}
	return uint(x.Hi >> 63), uint(bid.Bias128 - int(x.Hi>>bid.ExpShift128&bid.ExpMask128))
}

func isLongDecimal(x bid.Uint128) bool {
	if bid.NativeUBD128 {
		return bid.UBDIsLong128(ubdWords(x))
	}
	return bid.IsLong128(x)
}

// longParts returns the sign (0 or 1), the exponent and the coefficient of
// x, a value isLongDecimal accepts, for bid.PutLong128.
func longParts(x bid.Uint128) (sign uint, exp int, c bid.Uint128) {
	if bid.NativeUBD128 {
		return uint(x.Hi >> bid.UBDSignShift & 1), int(int64(x.Hi) >> bid.UBDExpShift), bid.Uint128{Hi: x.Hi & bid.UBDCoeffMaskHi, Lo: x.Lo}
	}
	return uint(x.Hi >> 63), int(x.Hi>>bid.ExpShift128&bid.ExpMask128) - bid.Bias128, bid.Uint128{Hi: x.Hi & bid.CoeffMask128Hi, Lo: x.Lo}
}

func unpackDecimal(x bid.Uint128) (kind bid.Kind, neg bool, coeff bid.Uint128, exp int) {
	if bid.NativeUBD128 {
		return bid.UBDUnpack128(ubdWords(x))
	}
	return bid.Unpack128(x)
}

func unpackDigitsDecimal(buf *[bid.Precision128]byte, x bid.Uint128) (kind bid.Kind, neg bool, n, exp int) {
	if bid.NativeUBD128 {
		return bid.UBDUnpackDigits128(buf, ubdWords(x))
	}
	return bid.UnpackDigits128(buf, x)
}

// decimal64Exact reports whether d is a finite decimal128 whose coefficient
// and exponent a decimal64 holds, as every decimal64 widened is: converting
// it to decimal64 changes nothing.
func decimal64Exact(d decimal128) bool {
	kind, _, coeff, exp := unpackDecimal(decimalWords(d))
	return kind == bid.KindFinite && coeff.Hi == 0 && coeff.Lo <= bid.MaxCoeff64 &&
		bid.MinExp64 <= exp && exp <= bid.MaxExp64
}

// appendDecimalB appends the 'b' form of x: the coefficient in decimal, 'e',
// and the exponent of its last digit with its sign, as a float's 'b' writes
// its integer significand, 'p' and a power of two. "150e-2" is 1.50 and
// "0e+0" the zero value. NaN and the infinities are written as for every
// format.
func appendDecimalB(dst []byte, x bid.Uint128) []byte {
	var digs [bid.Precision128]byte
	kind, neg, n, exp := unpackDigitsDecimal(&digs, x)
	switch kind {
	case bid.KindNaN:
		return append(dst, "NaN"...)
	case bid.KindInf:
		if neg {
			return append(dst, "-Inf"...)
		}
		return append(dst, "+Inf"...)
	}
	if neg {
		dst = append(dst, '-')
	}
	if n == 0 {
		dst = append(dst, '0')
	} else {
		dst = append(dst, digs[len(digs)-n:]...)
	}
	dst = append(dst, 'e')
	if exp >= 0 {
		dst = append(dst, '+')
	}
	return AppendInt(dst, int64(exp), 10)
}

// copyDecimalDigits copies a non-overlapping coefficient span; dst must be at
// least as long as src. Constant head and tail copies cover medium spans,
// with identical overlapping stores
// when the length lies between the two chunk sizes. Smaller and larger spans
// retain the general copy operation.
func copyDecimalDigits(dst, src []byte) {
	const word = 8
	n := len(src)
	if n >= word && n <= 4*word {
		dst = dst[:n]
		if n <= 2*word {
			copy(dst[:word], src[:word])
			copy(dst[n-word:], src[n-word:])
		} else {
			copy(dst[:2*word], src[:2*word])
			copy(dst[n-2*word:], src[n-2*word:])
		}
		return
	}
	copy(dst, src)
}

// parseDecimal converts a string to a decimal value of the given bitSize, as
// [ParseDecimal] documents.
//
//go:linkname parseDecimal
func parseDecimal(s string, bitSize int) (decimal128, error) {
	d, st := readDecimal(s, bitSize)
	if st&bid.Syntax != 0 {
		return 0, syntaxError("ParseDecimal", s)
	}
	if st&bid.Overflow != 0 {
		return d, rangeError("ParseDecimal", s)
	}
	return d, nil
}

// --- Coefficient digits ---

// A finite holds the coefficient digits of a finite value: the value
// is (-1)^neg × digs[len(digs)-n:] × 10^exp. There are no leading zeros;
// n is zero for a zero value, whatever its exponent.
type finite struct {
	neg  bool
	n    int
	exp  int
	digs *[bid.Precision128]byte
}

// round rounds the value to the precision that format and prec call for:
// prec+1 significant digits for 'e', prec significant digits for 'g' (one
// if prec is zero) and prec places after the point for 'f'. It does nothing
// if the value has no more digits than that. The rounding is the kernel's
// Quantize to nearest even; x is the encoding of the value.
func (v *finite) round(x bid.Uint128, format byte, prec int) {
	var keep int // significant digits to keep, or -1 for none in particular
	var exp int  // the exponent of the least significant digit kept
	switch format {
	case 'e', 'E':
		keep = prec + 1
		exp = v.exp + v.n - keep
	case 'g', 'G':
		keep = max(prec, 1)
		exp = v.exp + v.n - keep
	default: // 'f'
		keep = -1
		exp = -prec
	}
	drop := exp - v.exp // digits to discard
	if drop <= 0 {
		return
	}
	if drop > v.n {
		// The value is below a tenth of the last place kept.
		v.n = 0
		return
	}

	// Quantize works on the encoding. The value has the exponent v.exp,
	// which may put the quantum out of the format's range (the exponent of
	// a decimal with 34 digits is 6111 at most; the quantum may be 6144),
	// so quantize the coefficient alone, at exponent zero, and put the
	// exponent back afterwards.
	_, neg, coeff, _ := unpackDecimal(x)
	var q bid.Uint128
	if bid.NativeUBD128 {
		// UBD: the sign and the coefficient at exponent zero, and the
		// quantum's exponent, are fields; nothing packs.
		c := bid.UBD128{Lo: coeff.Lo, Hi: coeff.Hi}
		if neg {
			c.Hi |= bid.UBDSignHi
		}
		r := bid.UBDQuantizeMode128(c, bid.UBD128{Lo: 1, Hi: uint64(drop) << bid.UBDExpShift}, bid.ToNearestEven)
		q = bid.Uint128{Hi: r.Hi, Lo: r.Lo}
	} else {
		c, _ := bid.Pack128(neg, coeff, 0)
		quantum, _ := bid.Pack128(false, bid.Uint128{Lo: 1}, drop)
		q = bid.Quantize128(c, quantum, bid.ToNearestEven)
	}

	_, _, n, qexp := unpackDigitsDecimal(v.digs, q)
	v.n = n
	v.exp += qexp
	if keep > 0 && v.n > keep {
		// A carry made 9.99 into 10.0. The extra digit is a zero.
		// Keep the leading digits right-aligned after dropping that zero.
		copy(v.digs[len(v.digs)-keep:], v.digs[len(v.digs)-v.n:len(v.digs)-v.n+keep])
		v.exp += v.n - keep
		v.n = keep
	}
}

// --- Layout ---

// normalFormat is the verb that formatDigits lays out for fmt, one of the
// verbs appendDecimal lays out: 'e', 'E', 'f', 'g' and 'G'.
func normalFormat(fmt byte) byte {
	switch fmt {
	case 'e', 'E', 'f', 'g', 'G':
		return fmt
	}
	return 'g'
}

// appendZero appends a zero of the given sign.
func appendZero(dst []byte, neg bool, format byte, prec int) []byte {
	if neg {
		dst = append(dst, '-')
	}
	switch format {
	case 'e', 'E':
		if prec <= 0 {
			dst = append(dst, '0', format)
			return append(dst, "+00"...)
		}
		dst = append(dst, "0."...)
		for i := 0; i < prec; i++ {
			dst = append(dst, '0')
		}
		dst = append(dst, format)
		return append(dst, "+00"...)
	case 'g', 'G':
		// %g strips trailing zeros, so zero is always "0".
		// The fmt layer's # flag restores trailing zeros if needed.
		return append(dst, '0')
	default: // 'f'
		if prec <= 0 {
			return append(dst, '0')
		}
		dst = append(dst, "0."...)
		for i := 0; i < prec; i++ {
			dst = append(dst, '0')
		}
		return dst
	}
}

// Exponents of the leading digit outside this range use exponent notation in
// the canonical string. They are those of a float's shortest 'g' form
// (ftoa.go: "if shortest { eprec = 6 }").
const (
	canonicalMinExp = -4
	canonicalMaxExp = 6
)

// formatDigits formats the non-zero value (-1)^neg × digits × 10^exp, where
// format is one of 'e', 'E', 'f', 'g' and 'G' and prec is not negative. The
// digits are already rounded to prec.
func formatDigits(dst []byte, neg bool, exp int, digits []byte, format byte, prec int) []byte {
	ndigits := len(digits)

	if neg {
		dst = append(dst, '-')
	}

	switch format {
	case 'e', 'E':
		return appendExp(dst, digits, exp, format, prec)
	case 'f':
		return appendFixed(dst, digits, exp, prec)
	}

	// 'g' uses 'e' for large/small exponents, 'f' otherwise, and shows no
	// trailing zeros after the point and no point without digits after
	// it. The zeros come off the digits before anything is laid out, so
	// that nothing is appended only to be removed: dst may carry a prefix
	// that is not this function's to read, and its spare capacity is not
	// this function's to write beyond the result.
	ef := byte('e')
	if format == 'G' {
		ef = 'E'
	}
	e := exp + ndigits - 1
	p := max(prec, 1)
	for ndigits > 1 && digits[ndigits-1] == '0' {
		ndigits--
		exp++
	}
	digits = digits[:ndigits]
	if e >= -4 && e < p {
		return appendFixed(dst, digits, exp, max(-exp, 0))
	}
	return appendExp(dst, digits, exp, ef, ndigits-1)
}

// appendFixed formats in fixed-point notation. If prec is not negative the
// digits have at most prec places after the point; fewer are padded with
// zeros.
func appendFixed(dst []byte, digits []byte, exp int, prec int) []byte {
	ndigits := len(digits)
	// intPart = ndigits + exp (digits before the decimal point)
	intPart := ndigits + exp

	if intPart <= 0 {
		// 0.000...digits
		dst = append(dst, '0')
		if prec != 0 && (prec < 0 && ndigits > 0 || prec > 0) {
			dst = append(dst, '.')
			leading := -intPart
			for i := 0; i < leading; i++ {
				dst = append(dst, '0')
			}
			dst = append(dst, digits...)
			if prec > 0 {
				written := leading + ndigits
				for written < prec {
					dst = append(dst, '0')
					written++
				}
			}
		}
	} else if intPart >= ndigits {
		// All digits are before the decimal point.
		dst = append(dst, digits...)
		for i := ndigits; i < intPart; i++ {
			dst = append(dst, '0')
		}
		if prec > 0 {
			dst = append(dst, '.')
			for i := 0; i < prec; i++ {
				dst = append(dst, '0')
			}
		}
	} else {
		// Decimal point within digits.
		dst = append(dst, digits[:intPart]...)
		if prec != 0 {
			dst = append(dst, '.')
			dst = append(dst, digits[intPart:]...)
			if prec > 0 {
				written := ndigits - intPart
				for written < prec {
					dst = append(dst, '0')
					written++
				}
			}
		}
	}
	return dst
}

// appendExp formats in scientific notation. If prec is not negative the
// digits are at most prec+1; fewer are padded with zeros.
func appendExp(dst []byte, digits []byte, exp int, format byte, prec int) []byte {
	ndigits := len(digits)

	// Value is digits[0].digits[1:] × 10^e  where e = exp + ndigits - 1
	e := exp + ndigits - 1

	dst = append(dst, digits[0])
	fracDigits := ndigits - 1
	if prec > 0 || (prec < 0 && fracDigits > 0) {
		dst = append(dst, '.')
		dst = append(dst, digits[1:1+fracDigits]...)
		// Pad with zeros if needed.
		if prec > 0 {
			for i := fracDigits; i < prec; i++ {
				dst = append(dst, '0')
			}
		}
	}

	dst = append(dst, format)
	if e < 0 {
		dst = append(dst, '-')
		e = -e
	} else {
		dst = append(dst, '+')
	}
	// BID128 exponents can reach ~6176, requiring up to 4 digits.
	if e >= 1000 {
		dst = append(dst, byte(e/1000)+'0')
	}
	if e >= 100 {
		dst = append(dst, byte(e/100%10)+'0')
	}
	if e >= 10 {
		dst = append(dst, byte(e/10%10)+'0')
	} else {
		dst = append(dst, '0')
	}
	dst = append(dst, byte(e%10)+'0')
	return dst
}
