package strconv

// FormatDecimal converts the decimal value d to a string, according to the
// format fmt and precision prec. It rounds the result assuming that the
// original was obtained from a decimal value of bitSize bits (64 for
// decimal64, 128 for decimal128): with bitSize 64, d is first converted to
// decimal64, as [FormatFloat] converts its argument to float32 for bitSize
// 32. Any other bitSize panics, as it does for FormatFloat.
//
// The format fmt is one of
//   - 'b' (-ddddde±d, the coefficient and the exponent of its last digit,
//     both in decimal: 1.50 is "150e-2"; a float's 'b' writes its integer
//     significand and a power of two, and a decimal's radix is ten),
//   - 'e' (-d.dddde±dd, a decimal exponent),
//   - 'E' (-d.ddddE±dd, a decimal exponent),
//   - 'f' (-ddd.dddd, no exponent),
//   - 'g' ('e' for large exponents, 'f' otherwise),
//   - 'G' ('E' for large exponents, 'f' otherwise),
//   - 'x' (-0xh.hhhhp±dd, a hexadecimal fraction and binary exponent), or
//   - 'X' (-0Xh.hhhhP±dd, a hexadecimal fraction and binary exponent).
//
// 'x' and 'X' are laid out as FormatFloat lays them out, with a leading
// digit of 1 (or 0 for a zero), and write the value of d rounded to nearest,
// ties to even, at the number of hexadecimal digits asked for: most decimal
// values have no finite binary fraction, so that rounds as 'e' with a
// precision does. A decimal that is exactly a float64 value formats as
// FormatFloat formats that float64, at any precision a float64 has.
//
// Any other byte, as for FormatFloat, gives "%" followed by that byte for a
// finite value. NaN and the infinities are "NaN", "+Inf" and "-Inf" whatever
// the format, as for a float.
//
// The precision prec has FormatFloat's meaning, except for the special
// precision -1 with the decimal formats. For a binary float that means the
// fewest digits that round-trip the value. A decimal value also has a
// quantum, so with 'e', 'E', 'f', 'g' and 'G' it means all the digits of the
// coefficient: 1.50 formats as "1.50", and [ParseDecimal] of that string
// returns the same value and quantum. With 'x' and 'X' it means what it
// means for a float: the fewest digits for which ParseDecimal, at the same
// bitSize, returns the same value. Hexadecimal text has no quantum, so the
// value comes back but not the member of its cohort: 1.50 formats as
// "0x1.8p+00", which reads back as 1.5. 'b' ignores the precision, as it
// does for a float.
//
// With 'g' and 'G' and the special precision -1, the result is the canonical
// string. As for a float, it is in fixed notation unless the exponent of the
// leading digit is less than -4 or at least 6: 1234567.89 formats as
// "1.23456789e+06". Each member of a cohort has its own digits, so the
// notation is chosen by the value and the digits by the coefficient: the
// coefficient 1000000 with exponent 0 formats as "1.000000e+06", and 1E+6
// as "1e+06". The quantum above the units digit, which fixed notation can't
// show, also forces exponential notation: 1E+3 is "1e+03", not "1000".
func FormatDecimal(d decimal128, fmt byte, prec, bitSize int) string {
	if bitSize != 64 && bitSize != 128 {
		panic("strconv: illegal FormatDecimal bitSize")
	}
	return formatDecimal(narrowDecimal(d, bitSize), fmt, prec, bitSize)
}

// AppendDecimal appends the string form of the decimal value d,
// as generated by [FormatDecimal], to dst and returns the extended buffer.
func AppendDecimal(dst []byte, d decimal128, fmt byte, prec, bitSize int) []byte {
	if bitSize != 64 && bitSize != 128 {
		panic("strconv: illegal AppendDecimal bitSize")
	}
	return appendDecimal(dst, narrowDecimal(d, bitSize), fmt, prec, bitSize)
}

// narrowDecimal returns d rounded to the format of bitSize, 64 or 128.
func narrowDecimal(d decimal128, bitSize int) decimal128 {
	if bitSize == 64 && !decimal64Exact(d) {
		return decimal128(decimal64(d))
	}
	return d
}

// ParseDecimal converts the string s to a decimal value of the given bitSize,
// 64 for decimal64 or 128 for decimal128: the conversion from an external
// character sequence of IEEE 754-2019 clause 5.12. The result has type
// decimal128 whatever the bitSize; it converts to decimal64 without changing
// its value or quantum if bitSize is 64. A bitSize other than 64 is taken
// as 128.
//
// s is one of the following, with an optional sign:
//
//   - a decimal or hexadecimal numeral, in the syntax of Go's
//     [floating-point literals], underscores included;
//   - "Inf" or "Infinity", which gives an infinity of that sign
//     (clause 5.12.1);
//   - "NaN", which gives a quiet NaN (clause 5.12.1). The standard does not
//     interpret the sign of a NaN, and it is not kept: "-NaN" and "NaN" give
//     the same NaN.
//
// The words are matched ignoring case. "sNaN" is not accepted.
//
// A decimal numeral is converted as clause 5.12.2 requires: its value, sign
// and quantum are kept unless rounding is necessary, and a result that must
// be rounded is rounded correctly, with roundTiesToEven. So "1.50" is 1.50,
// not 1.5. A hexadecimal numeral (clause 5.12.3) has no quantum, and the
// result's exponent is chosen as for a constant without one (see
// "Conversions" in the Go specification): an exact value that is an integer
// that fits has exponent 0, another exact value has the smallest coefficient
// that holds it ("0x1p-2" is 0.25), and an inexact value, which is rounded
// once from the exact binary value, keeps every digit of the result.
//
// The errors that ParseDecimal returns have concrete type [*NumError] and
// include err.Num = s. If s is not syntactically well-formed, ParseDecimal
// returns zero and err.Err = ErrSyntax. If s is well-formed but rounds to a
// magnitude beyond the largest value of the size, ParseDecimal returns ±Inf
// and err.Err = ErrRange. A value too small for the format is not an error:
// it rounds to a subnormal value or to zero.
//
// [floating-point literals]: https://go.dev/ref/spec#Floating-point_literals
func ParseDecimal(s string, bitSize int) (decimal128, error) { return parseDecimal(s, bitSize) }
