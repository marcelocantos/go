//go:build goexperiment.decimal

package strconv

// FormatDecimal converts a decimal128 value to a string.
// The format fmt and precision prec follow the same rules as [FormatFloat],
// except for the special precision -1. For a binary float that means the
// fewest digits that round-trip the value. A decimal value also has a quantum,
// so it means all the digits of the coefficient: 1.50 formats as "1.50", and
// [ParseDecimal] of that string returns the same value and quantum.
//
// With 'g' and 'G' and the special precision -1, the result is the canonical
// string. It is in fixed notation unless the exponent of the leading digit is
// less than -4 or at least 21, or the quantum is above the units digit, which
// fixed notation can't show: 1e+03 is not 1000.
//
// The bitSize must be 64 for values from decimal64 or 128 for decimal128.
func FormatDecimal(d decimal128, fmt byte, prec, bitSize int) string {
	return formatDecimal(d, fmt, prec, bitSize)
}

// AppendDecimal appends the string form of the decimal128 value d,
// as generated by FormatDecimal, to dst and returns the extended buffer.
// The bitSize must be 64 for values widened from decimal64 or 128 for decimal128.
func AppendDecimal(dst []byte, d decimal128, fmt byte, prec, bitSize int) []byte {
	return appendDecimal(dst, d, fmt, prec, bitSize)
}

// ParseDecimal converts a string to a decimal value of the given bitSize, 64 or
// 128, rounded to nearest even from the exact value the string denotes. The
// result has type decimal128 whatever the bitSize, as [ParseFloat]'s result has
// type float64; it converts to decimal64 without changing its value or quantum
// if bitSize is 64.
//
// The string is a decimal numeral (an optional sign, digits with an optional
// point, and an optional exponent) or one of the words "inf", "infinity",
// "nan" and "snan", with an optional sign and in any case. Nothing else is
// accepted: no surrounding space, no underscores, no hexadecimal form, and
// no characters after a word. The quantum of the result is that of the numeral
// if the value is exact.
//
// If s is not syntactically well-formed, ParseDecimal returns zero and
// err.Err = ErrSyntax. If s is well-formed but rounds to a magnitude beyond the
// largest value of the size, ParseDecimal returns ±Inf and err.Err = ErrRange.
// As with [ParseFloat], a value too small for the format is not an error:
// it rounds to a subnormal value or to zero.
func ParseDecimal(s string, bitSize int) (decimal128, error) { return parseDecimal(s, bitSize) }
