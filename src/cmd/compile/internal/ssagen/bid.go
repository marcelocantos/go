const (
	bidAddMaxGap    = 14
	bidMaxWordPower = 19
	bidWordBytes    = 8
)

var bidAddPowers, bidComparePowers, bidRoundPowers *obj.LSym

// initBIDPowerTables declares synthesized literals before parallel SSA workers
// start. StringData caches per function; it cannot serialize a first declaration
// shared by several functions. Keep these bytes and indexes identical to the
// original tables so this changes declaration timing, not generated arithmetic.
func initBIDPowerTables() {
	var powers [(bidMaxWordPower + 1) * bidWordBytes]byte
	power := uint64(1)
	for i := 0; i <= bidMaxWordPower; i++ {
		Arch.LinkArch.ByteOrder.PutUint64(powers[i*bidWordBytes:], power)
		power *= 10
	}
	bidAddPowers = staticdata.StringSym(base.AutogeneratedPos, string(powers[:(bidAddMaxGap+1)*bidWordBytes]))
	bidComparePowers = staticdata.StringSym(base.AutogeneratedPos, string(powers[:]))
	bidRoundPowers = staticdata.StringSym(base.AutogeneratedPos, string(powers[bidWordBytes:]))
}

// bidConstZero recognizes exact constant storage at SSA construction time.
// Copies preserve bits; loads, phis and unresolved forward references remain
// unknown. Decode the storage XOR before checking numeric zero, including
// noncanonical encodings. The caller has excluded DPD targets.
func bidConstZero(x *ssa.Value) bool {
	kind := x.Type.Kind()
	for x.Op == ssaop.OpCopy {
		x = x.Args[0]
	}
	if kind == types.TDECIMAL64 {
		if x.Op == ssaop.OpConst64D || x.Op == ssaop.OpConst64 {
			return bid.IsZero64(uint64(x.AuxInt) ^ bid.Zero64)
		}
	} else if kind == types.TDECIMAL128 && x.Op == ssaop.OpDecimal128Make {
		lo, hi := x.Args[0], x.Args[1]
		if lo.Op == ssaop.OpConst64 && hi.Op == ssaop.OpConst64 {
			return bid.IsZero128(bid.BIDFromUBD128(bid.Uint128{Hi: uint64(hi.AuxInt), Lo: uint64(lo.AuxInt)}))
		}
	}
	return false
}

// bidIsZero compares a BID-native decimal with zero using integer SSA.
// Every finite noncanonical encoding also denotes zero. In particular,
// decimal128's second finite form always has an oversized coefficient;
// decimal64's second form can be canonical and needs its coefficient bound.
// The sign and quantum do not affect equality with zero. No memory operation
// or call is needed, and the operand has already been evaluated by s.expr.
func (s *state) bidIsZero(x *ssa.Value) *ssa.Value {
	u64, boolT := types.Types[types.TUINT64], types.Types[types.TBOOL]
	zero := s.constInt64(u64, 0)
	var hi, lo, coeff, noncanonical, form2 *ssa.Value
	_ = lo
	if x.Type.Kind() == types.TDECIMAL64 {
		hi = s.newValue2(ssaop.OpXor64, u64, s.newValue1(ssaop.OpCopy, u64, x), s.constInt64(u64, int64(bid.Zero64)))
		mask := s.constInt64(u64, int64(bid.Form2Mask64))
		form2 = s.newValue2(ssaop.OpEq64, boolT, s.newValue2(ssaop.OpAnd64, u64, hi, mask), mask)
		coeff = s.newValue2(ssaop.OpAnd64, u64, hi, s.constInt64(u64, 1<<bid.CoeffBits64-1))
		second := s.newValue2(ssaop.OpAnd64, u64, hi, s.constInt64(u64, 1<<bid.Form2CoeffBits64-1))
		// The implicit 2^53 bit is above the stored coefficient bits.
		limit := s.constInt64(u64, int64(bid.MaxCoeff64-(1<<bid.CoeffBits64)))
		noncanonical = s.newValue2(ssaop.OpAndB, boolT, form2, s.newValue2(ssaop.OpLess64U, boolT, limit, second))
		coeff = s.newValue2(ssaop.OpEq64, boolT, coeff, zero)
		coeff = s.newValue2(ssaop.OpAndB, boolT, s.newValue1(ssaop.OpNot, boolT, form2), coeff)
	} else {
		// UBD: a well-formed finite coefficient is at most MaxCoeff128
		// (the UBD kernel contract), so a finite value is zero exactly when
		// its 113 coefficient bits are clear. Every special value has the
		// 0x1F prefix in its coefficient bits, so none is zero by this test
		// and no tag test is needed: x is zero exactly when the high word
		// shifted past qExp and the sign, ORed with the low word, is 0.
		hi = s.newValue1(ssaop.OpDecimal128Hi, u64, x)
		lo = s.newValue1(ssaop.OpDecimal128Lo, u64, x)
		coeff = s.newValue2(ssaop.OpLsh64x64, u64, hi, s.constInt64(u64, 64-bid.UBDExpShift+1))
		return s.newValue2(ssaop.OpEq64, boolT, s.newValue2(ssaop.OpOr64, u64, coeff, lo), zero)
	}
	// SpecialMask64 is the same field in decimal128's high word.
	special := s.constInt64(u64, int64(bid.SpecialMask64))
	finite := s.newValue2(ssaop.OpNeq64, boolT, s.newValue2(ssaop.OpAnd64, u64, hi, special), special)
	return s.newValue2(ssaop.OpAndB, boolT, finite, s.newValue2(ssaop.OpOrB, boolT, coeff, noncanonical))
}

// bidCompareZero implements every comparison with a constant zero. Once NaNs
// and all encodings of zero are excluded, the sign alone determines ordering,
// including infinities. No decimal magnitude comparison or runtime call is
// needed. x has already been evaluated exactly once, in source order.
func (s *state) bidCompareZero(op ir.Op, x *ssa.Value, zeroOnLeft bool) *ssa.Value {
	isZero := s.bidIsZero(x)
	boolT, u64 := types.Types[types.TBOOL], types.Types[types.TUINT64]
	if op == ir.OEQ {
		return isZero
	}
	if op == ir.ONE {
		return s.newValue1(ssaop.OpNot, boolT, isZero)
	}
	if zeroOnLeft {
		switch op {
		case ir.OLT:
			op = ir.OGT
		case ir.OLE:
			op = ir.OGE
		case ir.OGT:
			op = ir.OLT
		case ir.OGE:
			op = ir.OLE
		}
	}
	if bidCallOnly(x) {
		return s.ubdCompareZeroOrdered(op, x)
	}
	var ordered, negative *ssa.Value
	if x.Type.Kind() == types.TDECIMAL64 {
		hi := s.newValue2(ssaop.OpXor64, u64, s.newValue1(ssaop.OpCopy, u64, x), s.constInt64(u64, int64(bid.Zero64)))
		mask := s.constInt64(u64, int64(bid.SpecialMask64|bid.NaNBit64))
		ordered = s.newValue2(ssaop.OpNeq64, boolT, s.newValue2(ssaop.OpAnd64, u64, hi, mask), mask)
		negative = s.newValue2(ssaop.OpLess64, boolT, hi, s.constInt64(u64, 0))
	} else {
		// UBD: a NaN's top five bits are its tag; the sign is bit 49.
		hi := s.newValue1(ssaop.OpDecimal128Hi, u64, x)
		tag := s.newValue2(ssaop.OpRsh64Ux64, u64, hi, s.constInt64(u64, 59))
		ordered = s.newValue2(ssaop.OpNeq64, boolT, tag, s.constInt64(u64, bid.UBDNaNTag))
		negative = s.newValue2(ssaop.OpNeq64, boolT, s.newValue2(ssaop.OpAnd64, u64, hi, s.constInt64(u64, bid.UBDSignHi)), s.constInt64(u64, 0))
	}
	var result *ssa.Value
	switch op {
	case ir.OLT:
		result = s.newValue2(ssaop.OpAndB, boolT, negative, s.newValue1(ssaop.OpNot, boolT, isZero))
	case ir.OLE:
		result = s.newValue2(ssaop.OpOrB, boolT, negative, isZero)
	case ir.OGT:
		result = s.newValue2(ssaop.OpAndB, boolT, s.newValue1(ssaop.OpNot, boolT, negative), s.newValue1(ssaop.OpNot, boolT, isZero))
	case ir.OGE:
		result = s.newValue2(ssaop.OpOrB, boolT, s.newValue1(ssaop.OpNot, boolT, negative), isZero)
	default:
		s.Fatalf("unexpected decimal zero comparison %v", op)
	}
	return s.newValue2(ssaop.OpAndB, boolT, ordered, result)
}

// ubdCompareZeroOrdered implements x < 0, x <= 0, x > 0 and x >= 0 for a
// well-formed (canonical) UBD x, at ubdLevel 7. v is the high word shifted
// past qExp, so that the sign is its top bit above the top 49 coefficient
// bits, with lo != 0 in the bits the shift cleared: v is negative exactly
// when x's sign is set, and 0 exactly when x is +0 (a canonical special has
// a nonzero coefficient, so it falls out by its sign). -0 makes v the least
// int64, which negation leaves alone. With NaN excluded by its tag:
//
//	x > 0   int64(v) > 0      x <= 0  int64(v) <= 0
//	x < 0   int64(-v) > 0     x >= 0  int64(-v) <= 0
//
// There is no slow path, so no call: the site needs no frame and spills
// nothing. Controlling a branch, x > 0 is 11 instructions on amd64 and 8 on
// arm64, against 10 and 9 for the call to ubdCompare128 it replaces.
func (s *state) ubdCompareZeroOrdered(op ir.Op, x *ssa.Value) *ssa.Value {
	boolT, u64, u8 := types.Types[types.TBOOL], types.Types[types.TUINT64], types.Types[types.TUINT8]
	hi := s.newValue1(ssaop.OpDecimal128Hi, u64, x)
	lo := s.newValue1(ssaop.OpDecimal128Lo, u64, x)
	zero := s.constInt64(u64, 0)
	nz := s.newValue1(ssaop.OpZeroExt8to64, u64, s.newValue1(ssaop.OpCvtBoolToUint8, u8, s.newValue2(ssaop.OpNeq64, boolT, lo, zero)))
	v := s.newValue2(ssaop.OpOr64, u64, s.newValue2(ssaop.OpLsh64x64, u64, hi, s.constInt64(u64, 64-bid.UBDExpShift)), nz)
	if op == ir.OLT || op == ir.OGE {
		v = s.newValue1(ssaop.OpNeg64, u64, v)
	}
	var result *ssa.Value
	if op == ir.OGT || op == ir.OLT {
		result = s.newValue2(ssaop.OpLess64, boolT, zero, v)
	} else {
		result = s.newValue2(ssaop.OpLeq64, boolT, v, zero)
	}
	tag := s.newValue2(ssaop.OpRsh64Ux64, u64, hi, s.constInt64(u64, 59))
	ordered := s.newValue2(ssaop.OpNeq64, boolT, tag, s.constInt64(u64, bid.UBDNaNTag))
	// A NaN branches to false rather than being ANDed in, so that where
	// the comparison controls a branch, the two tests are two branches.
	res := ssaMarker("ubdcmpzero")
	bNaN := s.f.NewBlock(block.BlockPlain)
	bAfter := s.f.NewBlock(block.BlockPlain)
	b := s.endBlock()
	b.Kind = block.BlockIf
	b.SetControl(ordered)
	b.Likely = ssa.BranchLikely
	bOrdered := s.f.NewBlock(block.BlockPlain)
	b.AddEdgeTo(bOrdered)
	b.AddEdgeTo(bNaN)
	s.startBlock(bOrdered)
	s.vars[res] = result
	s.endBlock().AddEdgeTo(bAfter)
	s.startBlock(bNaN)
	s.vars[res] = s.constBool(false)
	s.endBlock().AddEdgeTo(bAfter)
	s.startBlock(bAfter)
	r := s.variable(res, boolT)
	delete(s.vars, res)
	return r
}

// The kernel's general paths, which the compiler calls directly on the
// targets where it lowers the decimal128 operators to integer fast paths
// (bidKernelDirect). The runtime's functions for these operators are
// wrappers there: they pass the same four words on, add the rounding
// mode, and return what the kernel returns, at the cost of a frame and a
// second call on every operand pair the fast paths refuse. The UBD
// entries take each decimal128 as internal/bid.UBD128, its two words low
// first, the order in which it is passed in registers, so the operands go
// to the kernel where they already are, and the result comes back where
// it is returned. The operator entries take no rounding mode (the
// operators round ties to even); quantize and integral rounding pass the
// caller's as a fifth argument. The comparison
// returns its ordering and whether the operands are ordered, and the
// operator is decided here from the two.
var (
	bidKernelAdd, bidKernelSub, bidKernelMul, bidKernelDiv, bidKernelCmp *obj.LSym
	// The predicate entries, by operator (ubdLevel 8).
	bidKernelPred map[ir.Op]*obj.LSym
	// Quantize and integral rounding: the entries that take the caller's
	// mode, and those that round ties to even and take none.
	bidKernelQuantize, bidKernelIntegral       *obj.LSym
	bidKernelQuantizeTTE, bidKernelIntegralTTE *obj.LSym
	// The language's min and max, and its conversions to int64 and uint64.
	bidKernelMin, bidKernelMax          *obj.LSym
	bidKernelToInt64, bidKernelToUint64 *obj.LSym
)

func initBIDKernelSyms() {
	if !bidKernelDirect() {
		return
	}
	initBIDKernelSyms64()
	// The operators round ties to even: their entries take no mode.
	bidKernelAdd = base.PkgLinksym("internal/bid", "ubdAddTTE128", obj.ABIInternal)
	bidKernelSub = base.PkgLinksym("internal/bid", "ubdSubTTE128", obj.ABIInternal)
	bidKernelMul = base.PkgLinksym("internal/bid", "ubdMulTTE128", obj.ABIInternal)
	bidKernelDiv = base.PkgLinksym("internal/bid", "ubdDivTTE128", obj.ABIInternal)
	bidKernelCmp = base.PkgLinksym("internal/bid", "ubdCompare128", obj.ABIInternal)
	bidKernelPred = map[ir.Op]*obj.LSym{
		ir.OEQ: base.PkgLinksym("internal/bid", "ubdEqual128", obj.ABIInternal),
		ir.OLT: base.PkgLinksym("internal/bid", "ubdLess128", obj.ABIInternal),
		ir.OLE: base.PkgLinksym("internal/bid", "ubdLessEqual128", obj.ABIInternal),
		ir.OGT: base.PkgLinksym("internal/bid", "ubdGreater128", obj.ABIInternal),
		ir.OGE: base.PkgLinksym("internal/bid", "ubdGreaterEqual128", obj.ABIInternal),
	}
	bidKernelQuantize = base.PkgLinksym("internal/bid", "ubdQuantizeRnd128", obj.ABIInternal)
	bidKernelIntegral = base.PkgLinksym("internal/bid", "ubdRoundToIntegralRnd128", obj.ABIInternal)
	bidKernelQuantizeTTE = base.PkgLinksym("internal/bid", "ubdQuantizeTTE128", obj.ABIInternal)
	bidKernelIntegralTTE = base.PkgLinksym("internal/bid", "ubdRoundToIntegralTTE128", obj.ABIInternal)
	bidKernelMin = base.PkgLinksym("internal/bid", "ubdMin128", obj.ABIInternal)
	bidKernelMax = base.PkgLinksym("internal/bid", "ubdMax128", obj.ABIInternal)
	bidKernelToInt64 = base.PkgLinksym("internal/bid", "ubdInt64From128", obj.ABIInternal)
	bidKernelToUint64 = base.PkgLinksym("internal/bid", "ubdUint64From128", obj.ABIInternal)
}

// ubdLevel is the -d=ubdlevel setting, which chooses the fast paths of
// decimal128 operations on a UBD target. Every operation is its kernel
// call, and the levels add paths in front of it, one at a time, so that
// each can be measured:
//
//	1  the kernel call alone, the smallest code at each call site
//	2  and decimal128-go's first-level add path, for x + y and x - y
//	3  and its second-level add path, for both
//	4  the first level for x + y and the second for x - y
//	5  and decimal128-go's first-level multiply path, for x * y
//	6  and x == 0 and x != 0 inline, with no call
//	7  and x < 0, x <= 0, x > 0 and x >= 0 inline, with no call
//	8  and comparisons of two values call the kernel's predicate entries
//	9  and those comparisons have a fast path: one qExp and one sign (the default)
//
// Level -1 is the inline paths derived from the BID lowering instead,
// which handle more operand pairs inline at much greater size.
func ubdLevel() int {
	if base.Debug.UBDLevel == 0 {
		return 9
	}
	return base.Debug.UBDLevel
}

// bidCallOnly reports whether the decimal128 operation on x is lowered by
// ubdLevel's levels: its kernel call, with the level's fast paths if any.
func bidCallOnly(x *ssa.Value) bool {
	return ubdLevel() > 0 && x.Type.Kind() == types.TDECIMAL128 && bidKernelDirect()
}

// ubdAddFast lowers x + y or x - y on decimal128 to decimal128-go's add
// fast paths in front of the kernel call (ubdLevel 2 and up). For a
// difference y's sign is flipped first, so both paths see the effective
// signs; the kernel call receives the original y.
//
// First level (d128_add_rnd_ctxnull's fast entry): equal qExp and sign, the
// top 15 bits of the high words, and the high 49 coefficient bits of the
// operands summing below 2^48. Then y's coefficient is added straight onto
// x's whole stored value, so that x's qExp and sign ride along. The bound
// makes both coefficients below 2^112, so neither operand is special (a
// special's coefficient sets bit 48) and the sum is below 10^34: exact, with
// no rounding.
//
// Second level (level 3; the first test of d128_add_slow_rnd_ctxnull):
// equal qExp and opposite signs, the high words differing in the sign bit
// and the coefficient bits alone, and bit 48 clear in both. Each coefficient
// is then below 2^112, so neither operand is special, and the difference of
// the magnitudes, smaller than either, is exact at the common exponent.
// With x's sign flipped its top 15 bits are y's, so (xh ^ sign) - yh is the
// high word of xc - yc with no masking. A negative difference is negated
// and takes y's sign. An exact zero is +0: under IEEE 754-2019 clause 6.3 a
// cancellation is -0 only when rounding toward negative, and the operators
// round ties to even.
func (s *state) ubdAddFast(op ir.Op, rt *types.Type, x, y *ssa.Value) *ssa.Value {
	result := ssaMarker("ubdadd1") // one per lowering; see bidAddSub128
	u64, i64, boolT := types.Types[types.TUINT64], types.Types[types.TINT64], types.Types[types.TBOOL]
	zero := s.constInt64(u64, 0)
	signBit := s.constInt64(u64, bid.UBDSignHi)
	xh, yh := s.newValue1(ssaop.OpDecimal128Hi, u64, x), s.newValue1(ssaop.OpDecimal128Hi, u64, y)
	xl, yl := s.newValue1(ssaop.OpDecimal128Lo, u64, x), s.newValue1(ssaop.OpDecimal128Lo, u64, y)
	if op == ir.OSUB {
		yh = s.newValue2(ssaop.OpXor64, u64, yh, signBit)
	}
	coeffMask := s.constInt64(u64, int64(bid.UBDCoeffMaskHi))
	differ := s.newValue2(ssaop.OpXor64, u64, xh, yh)
	same := s.newValue2(ssaop.OpEq64, boolT, s.newValue2(ssaop.OpRsh64Ux64, u64, differ, s.constInt64(u64, bid.UBDExpShift-1)), zero)
	// The sum of the high coefficient bits without masking x: once the top
	// 15 bits are equal, xh = H + xc and yh = H + yc, so xc + yc is
	// (xh - yh) + 2*yc. Only the guard after the equality test reads it.
	// The register allocator issues a constant again at each use (a
	// 10-byte load on amd64), so masking x too would load the mask twice.
	ych := s.newValue2(ssaop.OpAnd64, u64, yh, coeffMask)
	coeffs := s.newValue2(ssaop.OpAdd64, u64, s.newValue2(ssaop.OpSub64, u64, xh, yh), s.newValue2(ssaop.OpAdd64, u64, ych, ych))
	fits := s.newValue2(ssaop.OpEq64, boolT, s.newValue2(ssaop.OpRsh64Ux64, u64, coeffs, s.constInt64(u64, 48)), zero)

	// Which levels this call site gets: level 2 the first, level 3 both,
	// level 4 the first for x + y and the second for x - y, the effective
	// operation of the common case, values of one sign.
	level := ubdLevel()
	first := level == 2 || level == 3 || level >= 4 && op == ir.OADD
	second := level == 3 || level >= 4 && op == ir.OSUB
	bSlow := s.f.NewBlock(block.BlockPlain)
	bAfter := s.f.NewBlock(block.BlockPlain)
	bOpposite := bSlow
	if second {
		bOpposite = s.f.NewBlock(block.BlockPlain)
	}
	guard := func(v *ssa.Value, fail *ssa.Block) {
		b := s.endBlock()
		b.Kind = block.BlockIf
		b.SetControl(v)
		next := s.f.NewBlock(block.BlockPlain)
		b.AddEdgeTo(next)
		b.AddEdgeTo(fail)
		s.startBlock(next)
	}
	var lo, hi *ssa.Value
	if first {
		guard(same, bOpposite)
		guard(fits, bSlow)
		sum := s.newValue3(ssaop.OpAdd64carry, types.NewTuple(u64, u64), xl, yl, zero)
		lo2, carry := s.newValue1(ssaop.OpSelect0, u64, sum), s.newValue1(ssaop.OpSelect1, u64, sum)
		hi2 := s.newValue1(ssaop.OpSelect0, u64, s.newValue3(ssaop.OpAdd64carry, types.NewTuple(u64, u64), xh, ych, carry))
		s.vars[result] = s.newValue2(ssaop.OpDecimal128Make, rt, lo2, hi2)
		s.endBlock().AddEdgeTo(bAfter)
	} else {
		s.endBlock().AddEdgeTo(bOpposite)
	}

	if second {
		s.startBlock(bOpposite)
		// Equal qExp and opposite signs: the top 15 bits differ in the
		// sign bit alone.
		guard(s.newValue2(ssaop.OpEq64, boolT, s.newValue2(ssaop.OpRsh64Ux64, u64, differ, s.constInt64(u64, bid.UBDExpShift-1)), s.constInt64(u64, 1)), bSlow)
		top := s.constInt64(u64, 1<<48)
		guard(s.newValue2(ssaop.OpEq64, boolT, s.newValue2(ssaop.OpAnd64, u64, s.newValue2(ssaop.OpOr64, u64, xh, yh), top), zero), bSlow)
		d := s.newValue3(ssaop.OpSub64borrow, types.NewTuple(u64, u64), xl, yl, zero)
		dlo := s.newValue1(ssaop.OpSelect0, u64, d)
		dhi := s.newValue1(ssaop.OpSelect0, u64, s.newValue3(ssaop.OpSub64borrow, types.NewTuple(u64, u64),
			s.newValue2(ssaop.OpXor64, u64, xh, signBit), yh, s.newValue1(ssaop.OpSelect1, u64, d)))
		// |xc - yc| < 2^112, so the high word's sign is the difference's.
		swap := s.newValue2(ssaop.OpLess64, boolT, s.newValue1(ssaop.OpCopy, i64, dhi), s.constInt64(i64, 0))
		n := s.newValue3(ssaop.OpSub64borrow, types.NewTuple(u64, u64), zero, dlo, zero)
		nlo := s.newValue1(ssaop.OpSelect0, u64, n)
		nhi := s.newValue1(ssaop.OpSelect0, u64, s.newValue3(ssaop.OpSub64borrow, types.NewTuple(u64, u64), zero, dhi, s.newValue1(ssaop.OpSelect1, u64, n)))
		lo = s.newValue3(ssaop.OpCondSelect, u64, nlo, dlo, swap)
		hi = s.newValue3(ssaop.OpCondSelect, u64, nhi, dhi, swap)
		// The header of the larger magnitude, its top 15 bits by two shifts
		// rather than a second 10-byte mask; +0 for an exact zero.
		hsel := s.newValue3(ssaop.OpCondSelect, u64, yh, xh, swap)
		header := s.newValue2(ssaop.OpLsh64x64, u64, s.newValue2(ssaop.OpRsh64Ux64, u64, hsel, s.constInt64(u64, bid.UBDExpShift-1)), s.constInt64(u64, bid.UBDExpShift-1))
		cancelled := s.newValue2(ssaop.OpEq64, boolT, s.newValue2(ssaop.OpOr64, u64, lo, hi), zero)
		header = s.newValue3(ssaop.OpCondSelect, u64, s.newValue2(ssaop.OpAnd64, u64, header, s.constInt64(u64, ^int64(bid.UBDSignHi))), header, cancelled)
		s.vars[result] = s.newValue2(ssaop.OpDecimal128Make, rt, lo, s.newValue2(ssaop.OpOr64, u64, header, hi))
		s.endBlock().AddEdgeTo(bAfter)
	}

	s.startBlock(bSlow)
	s.vars[result] = s.softDecimalOp(op, rt, x, y)
	s.endBlock().AddEdgeTo(bAfter)
	s.startBlock(bAfter)
	r := s.variable(result, rt)
	delete(s.vars, result)
	return r
}

// ubdMulFast lowers x * y on decimal128 to a narrowed form of
// decimal128-go's first-level multiply path (d128_multiply_rnd_ctxnull's
// fast entry) in front of the kernel call (ubdLevel 5): both coefficients
// below 2^56, and the sum of the exponents in the format. The product of
// the two coefficients is then below 2^112, so below 10^34: the exact
// result at the sum of the exponents, the preferred one, with the sign the
// XOR of the operands' (a zero's included). Every other pair, the kernel
// call.
//
// The operand test is one expression and one branch: shifting the OR of
// the high words left past qExp and sign leaves their high coefficient
// bits, zero when both coefficients fit a word (which also rules out the
// special values, whose coefficients begin 0x1F there), and the OR of the
// low words shifted right by 56 is zero when both are below 2^56. The
// exponent test is one unsigned comparison of the sum biased by 6176,
// which rejects both overflow and underflow; the sum itself goes into the
// result's header.
//
// decimal128-go takes full 64-bit coefficients, and so would this path
// with the low-word test dropped and the product tested instead after the
// multiply: its high word shifted right by 48 must be zero (below 2^112).
// That costs a shift, a test and a third conditional branch at every call
// site: 2 more instructions on linux/amd64 (30 against 28) and 1 more on
// arm64 (21 against 20), measured with research/ubd-size. What it buys is
// the products of word coefficients of 2^56 (about 7.2e16) or more that
// still fit, which the narrowed path sends to the kernel.
func (s *state) ubdMulFast(rt *types.Type, x, y *ssa.Value) *ssa.Value {
	result := ssaMarker("ubdmul1") // one per lowering; see bidAddSub128
	u64, boolT := types.Types[types.TUINT64], types.Types[types.TBOOL]
	zero := s.constInt64(u64, 0)
	xh, yh := s.newValue1(ssaop.OpDecimal128Hi, u64, x), s.newValue1(ssaop.OpDecimal128Hi, u64, y)
	xl, yl := s.newValue1(ssaop.OpDecimal128Lo, u64, x), s.newValue1(ssaop.OpDecimal128Lo, u64, y)
	// Both coefficients below 2^56, so the product is below 2^112.
	small := s.newValue2(ssaop.OpRsh64Ux64, u64, s.newValue2(ssaop.OpOr64, u64, xl, yl), s.constInt64(u64, 56))
	words := s.newValue2(ssaop.OpEq64, boolT, s.newValue2(ssaop.OpOr64, u64, s.newValue2(ssaop.OpLsh64x64, u64, s.newValue2(ssaop.OpOr64, u64, xh, yh), s.constInt64(u64, 64-bid.UBDExpShift+1)), small), zero)
	shift := s.constInt64(u64, bid.UBDExpShift)
	exp := s.newValue2(ssaop.OpAdd64, u64, s.newValue2(ssaop.OpRsh64x64, u64, xh, shift), s.newValue2(ssaop.OpRsh64x64, u64, yh, shift))
	// One unsigned comparison of the biased sum rejects both underflow and
	// overflow.
	inRange := s.newValue2(ssaop.OpLeq64U, boolT, s.newValue2(ssaop.OpAdd64, u64, exp, s.constInt64(u64, -bid.MinExp128)), s.constInt64(u64, bid.MaxExp128-bid.MinExp128))

	bSlow := s.f.NewBlock(block.BlockPlain)
	bAfter := s.f.NewBlock(block.BlockPlain)
	guard := func(v *ssa.Value) {
		b := s.endBlock()
		b.Kind = block.BlockIf
		b.SetControl(v)
		next := s.f.NewBlock(block.BlockPlain)
		b.AddEdgeTo(next)
		b.AddEdgeTo(bSlow)
		s.startBlock(next)
	}
	guard(words)
	guard(inRange)
	product := s.newValue2(ssaop.OpMul64uhilo, types.NewTuple(u64, u64), xl, yl)
	phi, plo := s.newValue1(ssaop.OpSelect0, u64, product), s.newValue1(ssaop.OpSelect1, u64, product)
	sign := s.newValue2(ssaop.OpAnd64, u64, s.newValue2(ssaop.OpXor64, u64, xh, yh), s.constInt64(u64, bid.UBDSignHi))
	header := s.newValue2(ssaop.OpOr64, u64, sign, s.newValue2(ssaop.OpLsh64x64, u64, exp, shift))
	s.vars[result] = s.newValue2(ssaop.OpDecimal128Make, rt, plo, s.newValue2(ssaop.OpOr64, u64, header, phi))
	s.endBlock().AddEdgeTo(bAfter)

	s.startBlock(bSlow)
	s.vars[result] = s.softDecimalOp(ir.OMUL, rt, x, y)
	s.endBlock().AddEdgeTo(bAfter)
	s.startBlock(bAfter)
	r := s.variable(result, rt)
	delete(s.vars, result)
	return r
}

// ubdComparePred lowers the comparison op of two decimal128 values from
// ubdLevel 8 to a call to the kernel's predicate entry for op, whose bool
// result is the comparison's: x != y is !ubdEqual128(x, y). op is the
// source operator, before OGT and OGE are turned around, so the operands
// are passed where they are. From ubdLevel 9 a fast path comes first
// (ubdCompareFast).
func (s *state) ubdComparePred(op ir.Op, x, y *ssa.Value) *ssa.Value {
	u64 := types.Types[types.TUINT64]
	xhi, yhi := s.newValue1(ssaop.OpDecimal128Hi, u64, x), s.newValue1(ssaop.OpDecimal128Hi, u64, y)
	xlo, ylo := s.newValue1(ssaop.OpDecimal128Lo, u64, x), s.newValue1(ssaop.OpDecimal128Lo, u64, y)
	if ubdLevel() >= 9 {
		return s.ubdCompareFast(op, xlo, xhi, ylo, yhi)
	}
	return s.ubdComparePredCall(op, xlo, xhi, ylo, yhi)
}

// ubdComparePredCall is the predicate entry's call for op.
func (s *state) ubdComparePredCall(op ir.Op, xlo, xhi, ylo, yhi *ssa.Value) *ssa.Value {
	boolT := types.Types[types.TBOOL]
	fn := op
	if op == ir.ONE {
		fn = ir.OEQ
	}
	r := s.rtcall(bidKernelPred[fn], true, []*types.Type{boolT}, xlo, xhi, ylo, yhi)[0]
	if op == ir.ONE {
		r = s.newValue1(ssaop.OpNot, boolT, r)
	}
	return r
}

// ubdCompareFast lowers the comparison op of two decimal128 values at
// ubdLevel 9: inline when the operands have one qExp and one sign and are
// not NaN, else the predicate entry's call (ubdComparePredCall).
//
// With the top 15 bits of the high words equal, the 128-bit words compare
// as the coefficients do. A canonical value is equal to another of its
// qExp and sign exactly when the bits are, and two infinities of one sign
// are equal by their bits too; only a NaN, which has the qExp field of
// another NaN of its sign, needs its tag test. For a negative sign the
// order of the coefficients is reversed: XORing all four words with the
// sign mask m (all ones when negative) reverses unsigned order, so one
// borrow chain serves both signs:
//
//	x < y   x' < y'        x <= y  !(y' < x')
//	x > y   y' < x'        x >= y  !(x' < y')
func (s *state) ubdCompareFast(op ir.Op, xlo, xhi, ylo, yhi *ssa.Value) *ssa.Value {
	u64, boolT := types.Types[types.TUINT64], types.Types[types.TBOOL]
	zero := s.constInt64(u64, 0)
	res := ssaMarker("ubdcmp")
	bSlow := s.f.NewBlock(block.BlockPlain)
	bAfter := s.f.NewBlock(block.BlockPlain)
	guard := func(v *ssa.Value) {
		b := s.endBlock()
		b.Kind = block.BlockIf
		b.SetControl(v)
		b.Likely = ssa.BranchLikely
		next := s.f.NewBlock(block.BlockPlain)
		b.AddEdgeTo(next)
		b.AddEdgeTo(bSlow)
		s.startBlock(next)
	}
	differ := s.newValue2(ssaop.OpXor64, u64, xhi, yhi)
	guard(s.newValue2(ssaop.OpEq64, boolT, s.newValue2(ssaop.OpRsh64Ux64, u64, differ, s.constInt64(u64, bid.UBDExpShift-1)), zero))
	tag := s.newValue2(ssaop.OpRsh64Ux64, u64, xhi, s.constInt64(u64, 59))
	guard(s.newValue2(ssaop.OpNeq64, boolT, tag, s.constInt64(u64, bid.UBDNaNTag)))

	var r *ssa.Value
	switch op {
	case ir.OEQ, ir.ONE:
		bits := s.newValue2(ssaop.OpOr64, u64, differ, s.newValue2(ssaop.OpXor64, u64, xlo, ylo))
		if op == ir.OEQ {
			r = s.newValue2(ssaop.OpEq64, boolT, bits, zero)
		} else {
			r = s.newValue2(ssaop.OpNeq64, boolT, bits, zero)
		}
	default:
		m := s.newValue2(ssaop.OpRsh64x64, u64, s.newValue2(ssaop.OpLsh64x64, u64, xhi, s.constInt64(u64, 64-bid.UBDExpShift)), s.constInt64(u64, 63))
		xl, xh := s.newValue2(ssaop.OpXor64, u64, xlo, m), s.newValue2(ssaop.OpXor64, u64, xhi, m)
		yl, yh := s.newValue2(ssaop.OpXor64, u64, ylo, m), s.newValue2(ssaop.OpXor64, u64, yhi, m)
		// less reports whether (ah, al) < (bh, bl), unsigned: the borrow
		// out of their difference.
		less := func(al, ah, bl, bh *ssa.Value) *ssa.Value {
			lo := s.newValue3(ssaop.OpSub64borrow, types.NewTuple(u64, u64), al, bl, zero)
			hi := s.newValue3(ssaop.OpSub64borrow, types.NewTuple(u64, u64), ah, bh, s.newValue1(ssaop.OpSelect1, u64, lo))
			return s.newValue2(ssaop.OpNeq64, boolT, s.newValue1(ssaop.OpSelect1, u64, hi), zero)
		}
		switch op {
		case ir.OLT:
			r = less(xl, xh, yl, yh)
		case ir.OGT:
			r = less(yl, yh, xl, xh)
		case ir.OLE:
			r = s.newValue1(ssaop.OpNot, boolT, less(yl, yh, xl, xh))
		case ir.OGE:
			r = s.newValue1(ssaop.OpNot, boolT, less(xl, xh, yl, yh))
		}
	}
	s.vars[res] = r
	s.endBlock().AddEdgeTo(bAfter)

	s.startBlock(bSlow)
	s.vars[res] = s.ubdComparePredCall(op, xlo, xhi, ylo, yhi)
	s.endBlock().AddEdgeTo(bAfter)
	s.startBlock(bAfter)
	v := s.variable(res, boolT)
	delete(s.vars, res)
	return v
}

// bidKernelDirect reports whether the target takes the decimal128
// operators' general cases straight to internal/bid: the BID targets with
// the integer fast paths, where the native encoding is the kernel's.
func bidKernelDirect() bool {
	return !ir.DecimalDPD() && (Arch.LinkArch.Family == sys.ARM64 || Arch.LinkArch.Family == sys.AMD64)
}

// bidKernelOp calls the kernel's general path for the decimal128 operator
// op, the language's min and max among them, or returns nil for an
// operator it does not take. Operators round to nearest, ties to even.
func (s *state) bidKernelOp(op ir.Op, rt *types.Type, x, y *ssa.Value) *ssa.Value {
	u64, boolT := types.Types[types.TUINT64], types.Types[types.TBOOL]
	// UBD: the kernel's UBD entries take the stored words as they are, low
	// first, as they arrive in registers (internal/bid.UBD128).
	xhi := s.newValue1(ssaop.OpDecimal128Hi, u64, x)
	yhi := s.newValue1(ssaop.OpDecimal128Hi, u64, y)
	xlo, ylo := s.newValue1(ssaop.OpDecimal128Lo, u64, x), s.newValue1(ssaop.OpDecimal128Lo, u64, y)
	var fn *obj.LSym
	switch op {
	case ir.OEQ, ir.ONE, ir.OLT, ir.OLE:
		res := s.rtcall(bidKernelCmp, true, []*types.Type{types.Types[types.TINT64], boolT}, xlo, xhi, ylo, yhi)
		zero := s.constInt64(types.Types[types.TINT64], 0)
		var r *ssa.Value
		switch op {
		case ir.OLT:
			r = s.newValue2(ssaop.OpLess64, boolT, res[0], zero)
		case ir.OLE:
			r = s.newValue2(ssaop.OpLeq64, boolT, res[0], zero)
		default:
			r = s.newValue2(ssaop.OpEq64, boolT, res[0], zero)
		}
		// Unordered operands, a NaN among them, satisfy only !=.
		r = s.newValue2(ssaop.OpAndB, boolT, res[1], r)
		if op == ir.ONE {
			r = s.newValue1(ssaop.OpNot, boolT, r)
		}
		return r
	case ir.OADD:
		fn = bidKernelAdd
	case ir.OSUB:
		// The kernel negates y unless it is a NaN, which keeps its sign.
		fn = bidKernelSub
	case ir.OMUL:
		fn = bidKernelMul
	case ir.ODIV:
		fn = bidKernelDiv
	case ir.OMIN:
		fn = bidKernelMin
	case ir.OMAX:
		fn = bidKernelMax
	default:
		return nil
	}
	// One call for every operand: the kernel's entry tests for word
	// coefficients itself, first, as cheaply as a test here, which would
	// cost every call site a second call sequence. The operator entries
	// take no rounding mode: the operators round to nearest, ties to even.
	res := s.rtcall(fn, true, []*types.Type{u64, u64}, xlo, xhi, ylo, yhi)
	return s.newValue2(ssaop.OpDecimal128Make, rt, res[0], res[1])
}

// bidAddSub128 adds or subtracts coefficients directly where the result is
// exact.
//
// First, effective same-sign addition at one quantum, the first-level fast
// path of decimal128-go (d128_add_rnd_ctxnull): equal qExp and sign (the
// high words' top 15 bits), and the high 49 coefficient bits of the two
// operands summing below 2^48. That bound makes both coefficients below
// 2^112, so neither operand is special (a special's coefficient begins 0x1F,
// which sets bit 48 of the high word) and the sum, below 2^113 - 2^64 + 2,
// is below 10^34: exact at the common exponent, with no rounding and no
// clamping. y's coefficient is added straight onto x's whole stored value,
// so x's qExp and sign ride along and nothing is unpacked or repacked; the
// bound keeps the carry out of the sign. A negative zero keeps its sign. For
// subtraction, y's sign is flipped only in the fast paths; the fallback
// receives the original y, including its NaN sign.
//
// Next, effective subtraction at one quantum: stored high words that differ
// in the sign bit alone (x - y of one sign, or x + y of opposite signs). The
// same word and first-form guards on x hold for y, whose high word differs
// only in the sign. The coefficient difference xl - yl, negated when it
// borrows, is below 2^64 <= 10^34 and exact at the common exponent, the
// preferred one. Its sign is x's when xl >= yl and the other sign when the
// difference borrows. An exact zero difference is +0: under IEEE 754-2019
// clause 6.3 a cancellation is -0 only when rounding toward negative, and the
// operators always round to nearest, ties to even. Without this branch these
// operands took the aligned path below at a gap of zero: a table load, a
// multiply by one and the general sign selection.
//
// Both operands were evaluated before this method. Only the slow branch calls
// the runtime, with the original operands. The normal variable/memory phis at
// bAfter join that call's memory with the unchanged fast-branch memory.
func (s *state) bidAddSub128(op ir.Op, rt *types.Type, x, y *ssa.Value) *ssa.Value {
	// The paths below merge through a variable of their own, as ternary
	// does. The phi builder for functions of more than smallBlocks blocks
	// gives a variable the type of the first read it meets, so a marker
	// shared by every lowering would give a function that lowers both
	// decimal widths a phi of the wrong width.
	result := ssaMarker("bidadd")
	u64, boolT := types.Types[types.TUINT64], types.Types[types.TBOOL]
	zero := s.constInt64(u64, 0)
	xh := s.newValue1(ssaop.OpDecimal128Hi, u64, x)
	yh := s.newValue1(ssaop.OpDecimal128Hi, u64, y)
	// UBD: the sign is bit 49, the exponent a signed shift away, and no
	// second form or storage mask exists. A word coefficient (the high
	// coefficient bits clear) also rules out every special value, whose
	// coefficient begins 0x1F, so no separate finiteness guard is needed.
	signMask := uint64(bid.UBDSignHi)
	signBit := s.constInt64(u64, int64(signMask))
	if op == ir.OSUB {
		yh = s.newValue2(ssaop.OpXor64, u64, yh, signBit)
	}
	xl := s.newValue1(ssaop.OpDecimal128Lo, u64, x)
	yl := s.newValue1(ssaop.OpDecimal128Lo, u64, y)
	coeffMask := s.constInt64(u64, int64(bid.UBDCoeffMaskHi))
	// Equal qExp and sign: the high words agree in their top 15 bits. The
	// opposite-sign path below tests the same difference.
	differ := s.newValue2(ssaop.OpXor64, u64, xh, yh)
	same := s.newValue2(ssaop.OpEq64, boolT, s.newValue2(ssaop.OpRsh64Ux64, u64, differ, s.constInt64(u64, bid.UBDExpShift-1)), zero)
	ych := s.newValue2(ssaop.OpAnd64, u64, yh, coeffMask)
	coeffs := s.newValue2(ssaop.OpAdd64, u64, s.newValue2(ssaop.OpAnd64, u64, xh, coeffMask), ych)
	fits := s.newValue2(ssaop.OpEq64, boolT, s.newValue2(ssaop.OpRsh64Ux64, u64, coeffs, s.constInt64(u64, 48)), zero)
	coeff := s.newValue2(ssaop.OpAnd64, u64, xh, coeffMask)
	word := s.newValue2(ssaop.OpEq64, boolT, coeff, zero)

	bSlow := s.f.NewBlock(block.BlockPlain)
	bAfter := s.f.NewBlock(block.BlockPlain)
	bAlign := s.f.NewBlock(block.BlockPlain)
	bOpposite := s.f.NewBlock(block.BlockPlain)
	// Short-circuit the guards, particularly the common mismatch in quantum
	// or sign. Branches also let the backend use condition codes directly
	// instead of materializing and combining three boolean values.
	for i, guard := range []*ssa.Value{same, fits} {
		b := s.endBlock()
		b.Kind = block.BlockIf
		b.SetControl(guard)
		next := s.f.NewBlock(block.BlockPlain)
		b.AddEdgeTo(next)
		if i == 0 {
			// A sign or quantum mismatch may still have an exact result.
			b.AddEdgeTo(bOpposite)
		} else {
			b.AddEdgeTo(bSlow)
		}
		s.startBlock(next)
	}

	sum := s.newValue3(ssaop.OpAdd64carry, types.NewTuple(u64, u64), xl, yl, zero)
	lo := s.newValue1(ssaop.OpSelect0, u64, sum)
	carry := s.newValue1(ssaop.OpSelect1, u64, sum)
	hi := s.newValue3(ssaop.OpAdd64carry, types.NewTuple(u64, u64), xh, ych, carry)
	hi = s.newValue1(ssaop.OpSelect0, u64, hi)
	s.vars[result] = s.newValue2(ssaop.OpDecimal128Make, rt, lo, hi)
	s.endBlock().AddEdgeTo(bAfter)

	s.startBlock(bOpposite)
	opposite := s.newValue2(ssaop.OpEq64, boolT, differ, signBit)
	for i, guard := range []*ssa.Value{opposite, word} {
		b := s.endBlock()
		b.Kind = block.BlockIf
		b.SetControl(guard)
		next := s.f.NewBlock(block.BlockPlain)
		b.AddEdgeTo(next)
		if i == 0 {
			b.AddEdgeTo(bAlign)
		} else {
			b.AddEdgeTo(bSlow)
		}
		s.startBlock(next)
	}
	diff := s.newValue3(ssaop.OpSub64borrow, types.NewTuple(u64, u64), xl, yl, zero)
	lo = s.newValue1(ssaop.OpSelect0, u64, diff)
	borrow := s.newValue1(ssaop.OpSelect1, u64, diff)
	borrowed := s.newValue2(ssaop.OpNeq64, boolT, borrow, zero)
	lo = s.newValue3(ssaop.OpCondSelect, u64, s.newValue1(ssaop.OpNeg64, u64, lo), lo, borrowed)
	hi = s.newValue2(ssaop.OpXor64, u64, xh, s.newValue2(ssaop.OpLsh64x64, u64, borrow, s.constInt64(u64, 49)))
	cancelled := s.newValue2(ssaop.OpEq64, boolT, lo, zero)
	hi = s.newValue3(ssaop.OpCondSelect, u64, s.newValue2(ssaop.OpAnd64, u64, hi, s.constInt64(u64, int64(^signMask))), hi, cancelled)
	s.vars[result] = s.newValue2(ssaop.OpDecimal128Make, rt, lo, hi)
	s.endBlock().AddEdgeTo(bAfter)

	s.startBlock(bAlign)
	// For two uint64 coefficients and a quantum gap at most 14, the largest
	// aligned sum is (2^64-1)*(10^14+1) < 10^34. A difference is no larger.
	// Both are exact at the smaller input exponent, including subnormals.
	const maxGap = bidAddMaxGap
	highs := s.newValue2(ssaop.OpAnd64, u64, s.newValue2(ssaop.OpOr64, u64, xh, yh), coeffMask)
	words := s.newValue2(ssaop.OpEq64, boolT, highs, zero)
	for _, guard := range []*ssa.Value{words} {
		b := s.endBlock()
		b.Kind = block.BlockIf
		b.SetControl(guard)
		next := s.f.NewBlock(block.BlockPlain)
		b.AddEdgeTo(next)
		b.AddEdgeTo(bSlow)
		s.startBlock(next)
	}
	shift := s.constInt64(u64, bid.UBDExpShift)
	xe := s.newValue2(ssaop.OpRsh64x64, u64, xh, shift)
	ye := s.newValue2(ssaop.OpRsh64x64, u64, yh, shift)
	swap := s.newValue2(ssaop.OpLess64, boolT, xe, ye)
	gap := s.newValue3(ssaop.OpCondSelect, u64,
		s.newValue2(ssaop.OpSub64, u64, ye, xe), s.newValue2(ssaop.OpSub64, u64, xe, ye), swap)
	bounded := s.newValue2(ssaop.OpLeq64U, boolT, gap, s.constInt64(u64, maxGap))
	b := s.endBlock()
	b.Kind = block.BlockIf
	b.SetControl(bounded)
	bScale := s.f.NewBlock(block.BlockPlain)
	b.AddEdgeTo(bScale)
	b.AddEdgeTo(bSlow)
	s.startBlock(bScale)

	higher := s.newValue3(ssaop.OpCondSelect, u64, yl, xl, swap)
	lower := s.newValue3(ssaop.OpCondSelect, u64, xl, yl, swap)
	highHeader := s.newValue3(ssaop.OpCondSelect, u64, yh, xh, swap)
	lowHeader := s.newValue3(ssaop.OpCondSelect, u64, xh, yh, swap)
	// Use the compiler's immutable content-addressed literal data, not a
	// mutable runtime table. The guarded gap proves the load is in bounds.
	// The selected ARM64/AMD64 backends support unaligned uint64 loads.
	const wordBytes = bidWordBytes
	ptrT := types.NewPtr(u64)
	table := s.newValue1A(ssaop.OpAddr, ptrT, bidAddPowers, s.sb)
	index := s.newValue2(ssaop.OpMul64, u64, gap, s.constInt64(u64, wordBytes))
	power := s.rawLoad(u64, s.newValue2(ssaop.OpAddPtr, ptrT, table, index))
	product := s.newValue2(ssaop.OpMul64uhilo, types.NewTuple(u64, u64), higher, power)
	phi := s.newValue1(ssaop.OpSelect0, u64, product)
	plo := s.newValue1(ssaop.OpSelect1, u64, product)
	signs := s.newValue2(ssaop.OpAnd64, u64, s.newValue2(ssaop.OpXor64, u64, xh, yh), signBit)
	sameSign := s.newValue2(ssaop.OpEq64, boolT, signs, zero)
	b = s.endBlock()
	b.Kind = block.BlockIf
	b.SetControl(sameSign)
	bSum := s.f.NewBlock(block.BlockPlain)
	bDiff := s.f.NewBlock(block.BlockPlain)
	b.AddEdgeTo(bSum)
	b.AddEdgeTo(bDiff)
	s.startBlock(bSum)
	sum = s.newValue3(ssaop.OpAdd64carry, types.NewTuple(u64, u64), plo, lower, zero)
	lo = s.newValue1(ssaop.OpSelect0, u64, sum)
	carry = s.newValue1(ssaop.OpSelect1, u64, sum)
	hi = s.newValue2(ssaop.OpAdd64, u64, phi, carry)
	s.vars[result] = s.newValue2(ssaop.OpDecimal128Make, rt, lo, s.newValue2(ssaop.OpOr64, u64, lowHeader, hi))
	s.endBlock().AddEdgeTo(bAfter)

	s.startBlock(bDiff)
	// The lower-quantum operand has a word coefficient. It can exceed the
	// aligned operand only when that operand's high product word is zero.
	less := s.newValue2(ssaop.OpAndB, boolT,
		s.newValue2(ssaop.OpEq64, boolT, phi, zero), s.newValue2(ssaop.OpLess64U, boolT, plo, lower))
	diff = s.newValue3(ssaop.OpSub64borrow, types.NewTuple(u64, u64), plo, lower, zero)
	lo = s.newValue1(ssaop.OpSelect0, u64, diff)
	borrow = s.newValue1(ssaop.OpSelect1, u64, diff)
	hi = s.newValue2(ssaop.OpSub64, u64, phi, borrow)
	lo = s.newValue3(ssaop.OpCondSelect, u64, s.newValue2(ssaop.OpSub64, u64, lower, plo), lo, less)
	hi = s.newValue3(ssaop.OpCondSelect, u64, zero, hi, less)
	negative := s.newValue2(ssaop.OpAnd64, u64, s.newValue3(ssaop.OpCondSelect, u64, lowHeader, highHeader, less), signBit)
	isZero := s.newValue2(ssaop.OpEq64, boolT, s.newValue2(ssaop.OpOr64, u64, hi, lo), zero)
	// Cancellation under round-half-even gives +0 at the preferred quantum.
	negative = s.newValue3(ssaop.OpCondSelect, u64, zero, negative, isZero)
	header := s.newValue2(ssaop.OpAnd64, u64, lowHeader, s.constInt64(u64, int64(^signMask)))
	header = s.newValue2(ssaop.OpOr64, u64, header, negative)
	s.vars[result] = s.newValue2(ssaop.OpDecimal128Make, rt, lo, s.newValue2(ssaop.OpOr64, u64, header, hi))
	s.endBlock().AddEdgeTo(bAfter)

	s.startBlock(bSlow)
	s.vars[result] = s.softDecimalOp(op, rt, x, y)
	s.endBlock().AddEdgeTo(bAfter)

	s.startBlock(bAfter)
	r := s.variable(result, rt)
	delete(s.vars, result)
	return r
}

// bidMul128 multiplies two canonical finite word coefficients directly when
// the full product and the sum of exponents fit decimal128. Mul64uhilo gives
// the exact product, including every bit needed to decide the coefficient
// bound. An unsigned range check on the biased exponent sum rejects both
// underflow and overflow. Within these bounds the preferred quantum is the
// exponent sum, the sign is the XOR of the operand signs (also for zero), and
// no digit is discarded. This is an exact packing exception; every failed
// guard calls the original multiplication, which handles rounding, clamping,
// noncanonical encodings and specials.
func (s *state) bidMul128(rt *types.Type, x, y *ssa.Value) *ssa.Value {
	result := ssaMarker("bidmul") // one per lowering; see bidAddSub128
	u64, boolT := types.Types[types.TUINT64], types.Types[types.TBOOL]
	zero := s.constInt64(u64, 0)
	xh := s.newValue1(ssaop.OpDecimal128Hi, u64, x)
	yh := s.newValue1(ssaop.OpDecimal128Hi, u64, y)
	xl := s.newValue1(ssaop.OpDecimal128Lo, u64, x)
	yl := s.newValue1(ssaop.OpDecimal128Lo, u64, y)
	// UBD: word coefficients rule out the special values (see
	// bidAddSub128), so no finiteness guards.
	coeff := s.newValue2(ssaop.OpAnd64, u64, s.newValue2(ssaop.OpOr64, u64, xh, yh), s.constInt64(u64, int64(bid.UBDCoeffMaskHi)))
	words := s.newValue2(ssaop.OpEq64, boolT, coeff, zero)
	bSlow := s.f.NewBlock(block.BlockPlain)
	bAfter := s.f.NewBlock(block.BlockPlain)
	for _, guard := range []*ssa.Value{words} {
		b := s.endBlock()
		b.Kind = block.BlockIf
		b.SetControl(guard)
		next := s.f.NewBlock(block.BlockPlain)
		b.AddEdgeTo(next)
		b.AddEdgeTo(bSlow)
		s.startBlock(next)
	}

	shift := s.constInt64(u64, bid.UBDExpShift)
	xe := s.newValue2(ssaop.OpRsh64x64, u64, xh, shift)
	ye := s.newValue2(ssaop.OpRsh64x64, u64, yh, shift)
	exp := s.newValue2(ssaop.OpAdd64, u64, xe, ye)
	biased := s.newValue2(ssaop.OpAdd64, u64, exp, s.constInt64(u64, bid.Bias128))
	expOK := s.newValue2(ssaop.OpLeq64U, boolT, biased, s.constInt64(u64, bid.MaxExp128+bid.Bias128))
	b := s.endBlock()
	b.Kind = block.BlockIf
	b.SetControl(expOK)
	bProduct := s.f.NewBlock(block.BlockPlain)
	b.AddEdgeTo(bProduct)
	b.AddEdgeTo(bSlow)
	s.startBlock(bProduct)

	product := s.newValue2(ssaop.OpMul64uhilo, types.NewTuple(u64, u64), xl, yl)
	hi := s.newValue1(ssaop.OpSelect0, u64, product)
	lo := s.newValue1(ssaop.OpSelect1, u64, product)
	maxHi, maxLo := s.constInt64(u64, int64(bid.MaxCoeff128Hi)), s.constInt64(u64, int64(bid.MaxCoeff128Lo))
	// Most word products are well below the 34-digit limit. Only inspect
	// the low-word boundary when the high word cannot establish that.
	below := s.newValue2(ssaop.OpLess64U, boolT, hi, maxHi)
	b = s.endBlock()
	b.Kind = block.BlockIf
	b.SetControl(below)
	bExact := s.f.NewBlock(block.BlockPlain)
	bBoundary := s.f.NewBlock(block.BlockPlain)
	b.AddEdgeTo(bExact)
	b.AddEdgeTo(bBoundary)
	s.startBlock(bBoundary)
	coeffOK := s.newValue2(ssaop.OpAndB, boolT, s.newValue2(ssaop.OpEq64, boolT, hi, maxHi), s.newValue2(ssaop.OpLeq64U, boolT, lo, maxLo))
	b = s.endBlock()
	b.Kind = block.BlockIf
	b.SetControl(coeffOK)
	b.AddEdgeTo(bExact)
	b.AddEdgeTo(bSlow)
	s.startBlock(bExact)

	sign := s.newValue2(ssaop.OpAnd64, u64, s.newValue2(ssaop.OpXor64, u64, xh, yh), s.constInt64(u64, bid.UBDSignHi))
	header := s.newValue2(ssaop.OpOr64, u64, sign, s.newValue2(ssaop.OpLsh64x64, u64, exp, shift))
	s.vars[result] = s.newValue2(ssaop.OpDecimal128Make, rt, lo, s.newValue2(ssaop.OpOr64, u64, header, hi))
	s.endBlock().AddEdgeTo(bAfter)

	s.startBlock(bSlow)
	s.vars[result] = s.softDecimalOp(ir.OMUL, rt, x, y)
	s.endBlock().AddEdgeTo(bAfter)
	s.startBlock(bAfter)
	r := s.variable(result, rt)
	delete(s.vars, result)
	return r
}

// ubdIntConv lowers a conversion between decimal128 and int64 or uint64
// (fk and tk, after the caller has widened a narrower integer), or returns
// nil for any other. From an integer it is inline: the integer is the
// coefficient at exponent 0, so the magnitude is the low word and the high
// word holds only the sign, every integer exact. To an integer it is one
// call of the kernel's entry, which truncates toward zero.
func (s *state) ubdIntConv(v *ssa.Value, fk, tk types.Kind, rt *types.Type) *ssa.Value {
	u64 := types.Types[types.TUINT64]
	switch {
	case tk == types.TDECIMAL128 && fk == types.TUINT64:
		return s.newValue2(ssaop.OpDecimal128Make, rt, v, s.constInt64(u64, 0))
	case tk == types.TDECIMAL128 && fk == types.TINT64:
		// neg is all ones for a negative v: |v| is (v ^ neg) - neg, which
		// is right for the most negative v too, as a uint64.
		neg := s.newValue2(ssaop.OpRsh64x64, u64, v, s.constInt64(u64, 63))
		lo := s.newValue2(ssaop.OpSub64, u64, s.newValue2(ssaop.OpXor64, u64, v, neg), neg)
		hi := s.newValue2(ssaop.OpAnd64, u64, neg, s.constInt64(u64, bid.UBDSignHi))
		return s.newValue2(ssaop.OpDecimal128Make, rt, lo, hi)
	case fk == types.TDECIMAL128 && (tk == types.TINT64 || tk == types.TUINT64):
		fn := bidKernelToInt64
		if tk == types.TUINT64 {
			fn = bidKernelToUint64
		}
		lo, hi := s.newValue1(ssaop.OpDecimal128Lo, u64, v), s.newValue1(ssaop.OpDecimal128Hi, u64, v)
		return s.rtcall(fn, true, []*types.Type{rt}, lo, hi)[0]
	}
	return nil
}
