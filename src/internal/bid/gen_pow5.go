//go:build ignore

// gen_pow5.go writes pow5tab.go, the 128-bit approximations of the powers of
// five used by the binary-to-decimal conversion's fast path
// (fromfloat_fast.go). Run it from this directory with
//
//	go run gen_pow5.go
//
// TestPow5Approx recomputes both tables with math/big.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"math/big"
	"os"
)

// The table bounds; fromfloat_fast.go says where they come from.
const (
	pow5MulMax = 358 // the largest s of m × 5^s: 2^-1074 at decimal128
	pow5DivMax = 292 // the largest k of m × 2^j / 5^k: 2^1023 at decimal64
)

func main() {
	var b bytes.Buffer
	b.WriteString(`// Copyright 2026 The Go Authors. All rights reserved.
// Use of this source code is governed by a BSD-style
// license that can be found in the LICENSE file.

// Code generated by gen_pow5.go; DO NOT EDIT.

package bid

`)
	mask := new(big.Int).SetUint64(^uint64(0))
	word := func(x *big.Int) string {
		hi := new(big.Int).Rsh(x, 64)
		lo := new(big.Int).And(x, mask)
		return fmt.Sprintf("{0x%016x, 0x%016x}", hi, lo)
	}
	five := big.NewInt(5)
	fmt.Fprintf(&b, "// pow5MulTab[s] is 5^s when that fits 128 bits, and otherwise its leading\n")
	fmt.Fprintf(&b, "// 128 bits, ⌊5^s / 2^(len(5^s) - 128)⌋.\n")
	fmt.Fprintf(&b, "var pow5MulTab = [%d]Uint128{\n", pow5MulMax+1)
	for s := 0; s <= pow5MulMax; s++ {
		p := new(big.Int).Exp(five, big.NewInt(int64(s)), nil)
		if a := p.BitLen() - 128; a > 0 {
			p.Rsh(p, uint(a))
		}
		fmt.Fprintf(&b, "\t%s, // %d\n", word(p), s)
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "// pow5DivTab[k] is ⌈2^(len(5^k) + 127) / 5^k⌉, a 128-bit reciprocal of 5^k\n")
	fmt.Fprintf(&b, "// that is never exact for k >= 1. Entry 0 is unused and zero.\n")
	fmt.Fprintf(&b, "var pow5DivTab = [%d]Uint128{\n", pow5DivMax+1)
	b.WriteString("\t{0, 0}, // 0\n")
	for k := 1; k <= pow5DivMax; k++ {
		p := new(big.Int).Exp(five, big.NewInt(int64(k)), nil)
		n := new(big.Int).Lsh(big.NewInt(1), uint(p.BitLen()+127))
		q, r := new(big.Int).QuoRem(n, p, new(big.Int))
		if r.Sign() != 0 {
			q.Add(q, big.NewInt(1))
		}
		fmt.Fprintf(&b, "\t%s, // %d\n", word(q), k)
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("pow5tab.go", src, 0o666); err != nil {
		log.Fatal(err)
	}
}
