// gen_recip.go writes reciptab.go: the inverses of powers of five used by
// the exact division of recip128.go, and the powers of five of
// the binary-to-decimal fast path of fromfloat_fast.go. Run it from this
// directory with
//
//	go run gen_recip.go
//
// The reciprocals of powers of ten are in zpow10.go, written by gen_arith.go.
// TestDivExactPow10 and TestPow5Approx recompute the
// tables, or check every entry through its results, with math/big.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"math/big"
	"os"
)

// The table bounds. recip128.go and fromfloat_fast.go say where they come
// from.
const (
	pow10Max   = 38  // the last power of ten below 2^128
	pow5MulMax = 358 // the largest s of m × 5^s: 2^-1074 at decimal128
	pow5DivMax = 292 // the largest k of m × 2^j / 5^k: 2^1023 at decimal64
)

func main() {
	var b bytes.Buffer
	b.WriteString(`// Copyright 2026 The Go Authors. All rights reserved.
// Use of this source code is governed by a BSD-style
// license that can be found in the LICENSE file.

// Code generated by gen_recip.go; DO NOT EDIT.

package bid

`)
	mask := new(big.Int).SetUint64(^uint64(0))
	word := func(x *big.Int) string {
		hi := new(big.Int).Rsh(x, 64)
		lo := new(big.Int).And(x, mask)
		return fmt.Sprintf("{0x%016x, 0x%016x}", hi, lo)
	}
	one := big.NewInt(1)
	two128 := new(big.Int).Lsh(one, 128)
	top := new(big.Int).Sub(two128, one)
	pow := func(base, k int) *big.Int {
		return new(big.Int).Exp(big.NewInt(int64(base)), big.NewInt(int64(k)), nil)
	}

	b.WriteString("// divExact5tab128[k] is the inverse of 5^k modulo 2^128 and ⌊(2^128 - 1) /\n")
	b.WriteString("// 5^k⌋; see divExactPow10Recip128.\n")
	fmt.Fprintf(&b, "var divExact5tab128 = [%d]divExact5x128{\n", pow10Max+1)
	for k := 0; k <= pow10Max; k++ {
		p := pow(5, k)
		inv := new(big.Int).ModInverse(p, two128)
		fmt.Fprintf(&b, "\t{Uint128%s, Uint128%s}, // %d\n", word(inv), word(new(big.Int).Quo(top, p)), k)
	}
	b.WriteString("}\n\n")

	b.WriteString("// pow5MulTab[s] is 5^s when that fits 128 bits, and otherwise its leading\n")
	b.WriteString("// 128 bits, ⌊5^s / 2^(len(5^s) - 128)⌋.\n")
	fmt.Fprintf(&b, "var pow5MulTab = [%d]Uint128{\n", pow5MulMax+1)
	for s := 0; s <= pow5MulMax; s++ {
		p := pow(5, s)
		if a := p.BitLen() - 128; a > 0 {
			p.Rsh(p, uint(a))
		}
		fmt.Fprintf(&b, "\t%s, // %d\n", word(p), s)
	}
	b.WriteString("}\n\n")

	b.WriteString("// pow5DivTab[k] is ⌈2^(len(5^k) + 127) / 5^k⌉, a 128-bit reciprocal of 5^k\n")
	b.WriteString("// that is never exact for k >= 1. Entry 0 is unused and zero.\n")
	fmt.Fprintf(&b, "var pow5DivTab = [%d]Uint128{\n", pow5DivMax+1)
	b.WriteString("\t{0, 0}, // 0\n")
	for k := 1; k <= pow5DivMax; k++ {
		p := pow(5, k)
		n := new(big.Int).Lsh(one, uint(p.BitLen()+127))
		q, r := new(big.Int).QuoRem(n, p, new(big.Int))
		if r.Sign() != 0 {
			q.Add(q, one)
		}
		fmt.Fprintf(&b, "\t%s, // %d\n", word(q), k)
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("reciptab.go", src, 0o666); err != nil {
		log.Fatal(err)
	}
}
